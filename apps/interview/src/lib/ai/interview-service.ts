import type Anthropic from "@anthropic-ai/sdk";
import { getAnthropicClient, MODEL, MAX_OUTPUT_TOKENS } from "./client";
import { buildSystemPrompt, type InterviewType } from "./prompts";
import { SCORE_ANSWER_TOOL, type ScoreResult } from "./scoring";
import { db } from "@/lib/db";
import { questions, answers, feedback, systemPrompts } from "@/lib/db/schema";
import { eq, and, asc, desc } from "drizzle-orm";

// ── Types ─────────────────────────────────────────────────────────

interface GenerateQuestionResult {
  questionText: string;
  topic: string | null;
  tokensUsed: number;
}

export interface FeedbackResult {
  score: ScoreResult;
  narrativeFeedback: string;
  tokensUsed: number;
}

// ── Load system prompt from DB or fallback ────────────────────────

async function loadSystemPrompt(
  type: InterviewType,
  difficulty: string
): Promise<string | null> {
  const [prompt] = await db
    .select()
    .from(systemPrompts)
    .where(
      and(
        eq(systemPrompts.type, type),
        eq(systemPrompts.difficulty, difficulty as "easy" | "medium" | "hard"),
        eq(systemPrompts.isActive, true)
      )
    )
    .orderBy(desc(systemPrompts.version))
    .limit(1);
  return prompt?.content ?? null;
}

// ── Build conversation history for a session ──────────────────────

async function buildConversationHistory(
  sessionId: string
): Promise<Anthropic.Messages.MessageParam[]> {
  const sessionQuestions = await db
    .select()
    .from(questions)
    .where(eq(questions.sessionId, sessionId))
    .orderBy(asc(questions.questionIndex));

  const messages: Anthropic.Messages.MessageParam[] = [];

  for (const q of sessionQuestions) {
    // The question was generated by the assistant
    messages.push({ role: "assistant", content: q.text });

    // Check if there's an answer for this question
    const [answer] = await db
      .select()
      .from(answers)
      .where(eq(answers.questionId, q.id))
      .limit(1);

    if (answer) {
      messages.push({ role: "user", content: answer.text });

      // Check if there's feedback for this answer (include tool_use result)
      const [fb] = await db
        .select()
        .from(feedback)
        .where(eq(feedback.answerId, answer.id))
        .limit(1);

      if (fb) {
        // Represent the scored feedback as assistant response
        const feedbackContent: Anthropic.Messages.ContentBlockParam[] = [];
        if (fb.dimensions) {
          feedbackContent.push({
            type: "tool_use",
            id: `toolu_${fb.id.replace(/-/g, "").slice(0, 24)}`,
            name: "score_answer",
            input: {
              overall_score: fb.overallScore,
              dimensions: fb.dimensions,
              strengths: fb.strengths ?? [],
              improvements: fb.improvements ?? [],
              sample_answer_snippet: fb.sampleAnswerSnippet ?? "",
            },
          });
        }
        if (fb.feedbackText) {
          feedbackContent.push({ type: "text", text: fb.feedbackText });
        }
        if (feedbackContent.length > 0) {
          messages.push({ role: "assistant", content: feedbackContent });
          // Add tool result from user side so conversation is valid
          if (fb.dimensions) {
            messages.push({
              role: "user",
              content: [
                {
                  type: "tool_result",
                  tool_use_id: `toolu_${fb.id.replace(/-/g, "").slice(0, 24)}`,
                  content: "Score recorded.",
                },
              ],
            });
          }
        }
      }
    }
  }

  return messages;
}

// ── Generate a question ───────────────────────────────────────────

export async function generateQuestion(opts: {
  sessionId: string;
  type: InterviewType;
  difficulty: string;
  targetRole?: string | null;
  targetCompany?: string | null;
  questionIndex: number;
  totalQuestions: number;
}): Promise<GenerateQuestionResult> {
  const client = getAnthropicClient();

  const customPrompt = await loadSystemPrompt(opts.type, opts.difficulty);
  const systemPrompt = buildSystemPrompt(opts.type, {
    difficulty: opts.difficulty,
    targetRole: opts.targetRole,
    targetCompany: opts.targetCompany,
    questionIndex: opts.questionIndex,
    totalQuestions: opts.totalQuestions,
    customPrompt,
  });

  const history = await buildConversationHistory(opts.sessionId);

  // If this is the first question, add a user message to kick off
  const userMessages: Anthropic.Messages.MessageParam[] =
    history.length === 0
      ? [{ role: "user", content: "Please begin the interview with your first question." }]
      : [...history, { role: "user", content: "Please ask the next interview question." }];

  const response = await client.messages.create({
    model: MODEL,
    max_tokens: MAX_OUTPUT_TOKENS,
    system: systemPrompt,
    messages: userMessages,
  });

  const questionText = response.content
    .filter((b): b is Anthropic.Messages.TextBlock => b.type === "text")
    .map((b) => b.text)
    .join("\n\n");

  const tokensUsed =
    (response.usage?.input_tokens ?? 0) + (response.usage?.output_tokens ?? 0);

  return { questionText, topic: null, tokensUsed };
}

// ── Score an answer (streaming) ───────────────────────────────────

export async function scoreAnswerStreaming(opts: {
  sessionId: string;
  type: InterviewType;
  difficulty: string;
  targetRole?: string | null;
  targetCompany?: string | null;
  questionIndex: number;
  totalQuestions: number;
  questionText: string;
  answerText: string;
  onToken: (token: string) => void;
  onScore: (score: ScoreResult) => void;
  onComplete: (result: FeedbackResult) => void;
  onError: (error: Error) => void;
}): Promise<void> {
  const client = getAnthropicClient();

  const customPrompt = await loadSystemPrompt(opts.type, opts.difficulty);
  const systemPrompt = buildSystemPrompt(opts.type, {
    difficulty: opts.difficulty,
    targetRole: opts.targetRole,
    targetCompany: opts.targetCompany,
    questionIndex: opts.questionIndex,
    totalQuestions: opts.totalQuestions,
    customPrompt,
  });

  const history = await buildConversationHistory(opts.sessionId);

  // Add the current Q&A to history
  const messages: Anthropic.Messages.MessageParam[] = [
    ...history,
    // If the question isn't already in history (first question case)
    ...(history.length === 0
      ? [
          { role: "user" as const, content: "Please begin the interview with your first question." },
          { role: "assistant" as const, content: opts.questionText },
        ]
      : []),
    { role: "user", content: opts.answerText },
  ];

  const stream = await client.messages.create({
    model: MODEL,
    max_tokens: MAX_OUTPUT_TOKENS,
    system:
      systemPrompt +
      "\n\nIMPORTANT: You MUST call the score_answer tool first to provide structured scoring, then follow with narrative feedback text explaining your assessment.",
    messages,
    tools: [SCORE_ANSWER_TOOL],
    stream: true,
  });

  let narrativeFeedback = "";
  let score: ScoreResult | null = null;
  let currentToolInput = "";
  let inToolUse = false;
  let totalTokens = 0;

  for await (const event of stream) {
    switch (event.type) {
      case "content_block_start": {
        if (event.content_block.type === "tool_use") {
          inToolUse = true;
          currentToolInput = "";
        }
        break;
      }
      case "content_block_delta": {
        if (event.delta.type === "text_delta") {
          narrativeFeedback += event.delta.text;
          opts.onToken(event.delta.text);
        } else if (event.delta.type === "input_json_delta") {
          currentToolInput += event.delta.partial_json;
        }
        break;
      }
      case "content_block_stop": {
        if (inToolUse && currentToolInput) {
          try {
            score = JSON.parse(currentToolInput) as ScoreResult;
            opts.onScore(score);
          } catch {
            // Partial JSON — will be caught at completion
          }
          inToolUse = false;
        }
        break;
      }
      case "message_delta": {
        totalTokens =
          (event.usage?.output_tokens ?? 0);
        break;
      }
    }
  }

  if (!score) {
    opts.onError(new Error("Claude did not return a score_answer tool call"));
    return;
  }

  opts.onComplete({
    score,
    narrativeFeedback: narrativeFeedback.trim(),
    tokensUsed: totalTokens,
  });
}
