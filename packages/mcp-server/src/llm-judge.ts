/**
 * @preplai/mcp-server — LLM-as-Judge for Visual Script Quality
 *
 * Uses an LLM to evaluate presentation quality on dimensions that
 * heuristics cannot measure:
 *   1. Content Accuracy — Does the presentation correctly explain the topic?
 *   2. Coherence — Does the narrative flow logically across frames?
 *   3. Entity Appropriateness — Are the right entity types used for the topic?
 *
 * Inspired by PPTEval (EMNLP 2025) and Agent-as-Judge (arXiv 2508.02994).
 *
 * This module is decoupled from the heuristic scorer — it can be used
 * independently in evals or combined with scoreVisualScript() for a
 * comprehensive quality assessment.
 */

// ── Types ────────────────────────────────────────────────────────────────

export interface JudgeDimensionScore {
  score: number; // 1-10
  reasoning: string;
}

export interface LlmJudgeReport {
  contentAccuracy: JudgeDimensionScore;
  coherence: JudgeDimensionScore;
  entityAppropriateness: JudgeDimensionScore;
  overall: number; // 1-10 weighted average
  prompt: string;
  model: string;
  timestamp: string;
}

export interface LlmJudgeOptions {
  /** The original user prompt / topic */
  prompt: string;
  /** The visual script JSON to evaluate */
  visualScript: any;
  /** LLM provider function: (systemPrompt, userPrompt) => response text */
  provider: (systemPrompt: string, userPrompt: string) => Promise<string>;
  /** Model identifier for tracking */
  model: string;
}

// ── Rubric ───────────────────────────────────────────────────────────────

const JUDGE_SYSTEM_PROMPT = `You are an expert evaluator of visual presentations generated by AI. Your job is to score a presentation's quality across three dimensions.

You will receive:
1. The ORIGINAL PROMPT that the presentation was created for
2. The VISUAL SCRIPT JSON containing frames, entities, and narration

Score each dimension from 1-10 with reasoning:

## Dimension 1: Content Accuracy (1-10)
Does the presentation correctly explain the topic from the prompt?
- 9-10: All key concepts present, technically accurate, specific details
- 7-8: Mostly accurate, minor gaps or simplifications
- 5-6: Partially correct, missing important concepts
- 3-4: Significant inaccuracies or missing core concepts
- 1-2: Wrong or irrelevant content

## Dimension 2: Coherence (1-10)
Does the narrative flow logically from frame to frame?
- 9-10: Clear story arc (setup → build → resolution), each frame builds on previous
- 7-8: Mostly logical flow, minor jumps
- 5-6: Somewhat disjointed, frames don't build on each other well
- 3-4: Random ordering, hard to follow
- 1-2: No logical connection between frames

## Dimension 3: Entity Appropriateness (1-10)
Are the right visual entity types used for the topic?
- 9-10: Entity types perfectly match the domain (e.g., BinaryTree for tree topics, Server/Database for architecture)
- 7-8: Mostly appropriate, 1-2 generic entities that could be more specific
- 5-6: Mix of appropriate and generic entities
- 3-4: Mostly generic (Concept, Label) when specific types exist
- 1-2: Wrong entity types for the domain

RESPOND WITH ONLY valid JSON in this exact format (no markdown fences, no explanation outside JSON):
{
  "contentAccuracy": { "score": <1-10>, "reasoning": "<1-2 sentences>" },
  "coherence": { "score": <1-10>, "reasoning": "<1-2 sentences>" },
  "entityAppropriateness": { "score": <1-10>, "reasoning": "<1-2 sentences>" }
}`;

// ── Available entity types (for context) ─────────────────────────────────

const ENTITY_TYPE_CONTEXT = `Available entity types include: Server, Database, Cache, User, Cloud, Service, Queue, LoadBalancer, Container, Pod, Lambda, Pipeline, Monitor, Firewall, Network, Volume, CodeBlock, BinaryTree, Array, StepList, BigO, BarChart, Graph2D, CoordinateSystem, ProcessState, CallStack, Stack, HashTable, LinkedList, Table, Timeline, Deployment, Build, GitBranch, PullRequest, Rollback, CDN, StorageBucket, Alert, Trace, Dashboard, Schema, Token, AuthFlow, Event, Stream, Subnet, NeuralNetwork, FSM, RecursionTree, MemoryLayout, GanttChart, PieChart, Histogram, ErrorState, Task, Cycle, FlowDiagram, Concept, Arrow, DataFlow, H1, H2, H3, Label, Metric, Comparison, Callout, Definition.`;

// ── Dimension weights ────────────────────────────────────────────────────

const JUDGE_WEIGHTS = {
  contentAccuracy: 0.45,
  coherence: 0.30,
  entityAppropriateness: 0.25,
} as const;

// ── Serialise visual script for the judge ────────────────────────────────

function serialiseForJudge(visualScript: any): string {
  // Extract only the information the judge needs:
  // frames with entities (type, label, id, highlight) and narration
  const frames = (visualScript.frames ?? []).map((frame: any, i: number) => {
    const entities = (frame.entities ?? []).map((e: any) => ({
      id: e.id,
      type: e.type,
      label: e.label ?? e.l,
      highlight: e.highlight ?? false,
    }));
    return {
      frame: i + 1,
      narration: frame.narrationSegment ?? frame.n ?? '',
      entities,
    };
  });

  return JSON.stringify({ frames }, null, 2);
}

// ── Parse judge response ─────────────────────────────────────────────────

function parseJudgeResponse(text: string): {
  contentAccuracy: JudgeDimensionScore;
  coherence: JudgeDimensionScore;
  entityAppropriateness: JudgeDimensionScore;
} {
  const trimmed = text.trim()
    .replace(/^```(?:json)?\s*\n?/i, '')
    .replace(/\n?```\s*$/i, '')
    .trim();

  let parsed: any;
  try {
    parsed = JSON.parse(trimmed);
  } catch {
    // Try to extract JSON from response
    const match = trimmed.match(/\{[\s\S]*\}/);
    if (match) {
      parsed = JSON.parse(match[0]);
    } else {
      throw new Error(`Could not parse judge response: ${trimmed.slice(0, 200)}`);
    }
  }

  const extract = (key: string): JudgeDimensionScore => {
    const dim = parsed[key];
    if (!dim || typeof dim.score !== 'number') {
      return { score: 5, reasoning: 'Could not parse dimension score' };
    }
    return {
      score: Math.max(1, Math.min(10, Math.round(dim.score))),
      reasoning: String(dim.reasoning ?? ''),
    };
  };

  return {
    contentAccuracy: extract('contentAccuracy'),
    coherence: extract('coherence'),
    entityAppropriateness: extract('entityAppropriateness'),
  };
}

// ── Main judge function ──────────────────────────────────────────────────

/**
 * Evaluate a visual script using an LLM judge.
 *
 * Sends the presentation (frames, entities, narration) along with the
 * original prompt to an LLM, which scores content accuracy, coherence,
 * and entity appropriateness on a 1-10 scale.
 *
 * @returns LlmJudgeReport with per-dimension scores (1-10) and reasoning
 */
export async function judgeVisualScript(options: LlmJudgeOptions): Promise<LlmJudgeReport> {
  const { prompt, visualScript, provider, model } = options;

  const serialised = serialiseForJudge(visualScript);

  const userPrompt = `## Original Prompt
"${prompt}"

## Visual Script
${serialised}

## Entity Type Reference
${ENTITY_TYPE_CONTEXT}

Evaluate this presentation. Respond with ONLY the JSON object.`;

  const responseText = await provider(JUDGE_SYSTEM_PROMPT, userPrompt);
  const dimensions = parseJudgeResponse(responseText);

  const overall = Number(
    (
      dimensions.contentAccuracy.score * JUDGE_WEIGHTS.contentAccuracy +
      dimensions.coherence.score * JUDGE_WEIGHTS.coherence +
      dimensions.entityAppropriateness.score * JUDGE_WEIGHTS.entityAppropriateness
    ).toFixed(1),
  );

  return {
    ...dimensions,
    overall,
    prompt,
    model,
    timestamp: new Date().toISOString(),
  };
}

/**
 * Combine heuristic quality score (0-100) with LLM judge score (1-10)
 * into a single unified score (0-100).
 *
 * Heuristic = 40% weight (design/structure)
 * LLM Judge = 60% weight (content/coherence)
 *
 * This reflects the reality that content correctness matters more than
 * layout quality for the end user.
 */
export function combineScores(heuristicOverall: number, judgeOverall: number): number {
  // Normalize judge from 1-10 to 0-100
  const judgeNormalized = ((judgeOverall - 1) / 9) * 100;
  return Math.round(heuristicOverall * 0.4 + judgeNormalized * 0.6);
}
